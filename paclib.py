W=27
K=(0,0,0)
WH=(255,255,255)
PY=(255,230,0)
GC=((255,0,0),(255,160,255),(0,230,230),(255,170,70),(40,40,255))
D4=((0,-1),(-1,0),(0,1),(1,0))
KD={14:0,23:1,34:2,25:3}
CIR=[(a,b) for b in range(7) for a in range(7) if abs(a-3)<=(1,2,3,3,3,2,1)[b]]
dt=[0]*22

def dot(i):
    return (dt[i//W]>>i%W&1)*(1+(MZ[i]=="o"))

def box(x,y,w,h,c):
    for a in range(x,x+w):
        for b in range(y,y+h):
            set_pixel(a,b,c)

def ok(c,r):
    return 0<=c<W and MZ[r*W+c] not in "#x=H"

def tile(c,r):
    i=r*W+c
    x=4+c*8
    y=8+r*8
    box(x,y,8,8,(20,40,150) if MZ[i] in "#x" else K)
    d=dot(i)
    if d:box(x+4-d,y+4-d,2*d,2*d,(255,184,151))

def under(x,y):
    tile(x//8,y//8)
    tile((x+7)//8,(y+7)//8)

def text(y,s,c=K):
    box(228,y,156,18,WH)
    if s:draw_string(232,y,s,c)

def pmove(p,nd,st):
    if p[0]%8==0 and p[1]%8==0:
        c=p[0]//8
        r=p[1]//8
        i=r*W+c
        d=dot(i)
        if d:
            st[0]+=(10,50)[d-1]
            st[1]-=1
            if d==2:st[2]=1
            dt[r]&=~(1<<c)
        if c==0 and p[2]<0:p[0]=208
        if c==26 and p[2]>0:p[0]=0
        c=p[0]//8
        d=D4[nd]
        if ok(c+d[0],r+d[1]):p[2],p[3]=d
        if not ok(c+p[2],r+p[3]):p[2],p[3]=0,0
    elif D4[nd][0]==-p[2] and D4[nd][1]==-p[3]:p[2],p[3]=D4[nd]
    p[0]+=2*p[2]
    p[1]+=2*p[3]

def gmove(e,j,p):
    if e[0]%8==0 and e[1]%8==0:
        c=e[0]//8
        r=e[1]//8
        if c==0 and e[2]<0:
            e[0]=208
            c=26
        elif c==26 and e[2]>0:
            e[0]=0
            c=0
        tx=p[0]//8+(0,4,-4,0)[j]*p[2]
        ty=p[1]//8+(0,4,-4,0)[j]*p[3]
        if j==3 and (c-tx)**2+(r-ty)**2<64:tx,ty=0,22
        o=[q for q in D4 if (q[0]!=-e[2] or q[1]!=-e[3]) and ok(c+q[0],r+q[1])] or [(-e[2],-e[3])]
        q=o[randint(0,len(o)-1)]
        if not e[5]:
            for n in o:
                if (c+n[0]-tx)**2+(r+n[1]-ty)**2<(c+q[0]-tx)**2+(r+q[1]-ty)**2:q=n
        e[2],e[3]=q
    e[0]+=2*e[2]
    e[1]+=2*e[3]
